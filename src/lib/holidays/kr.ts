/** 'YYYY-MM-DD' → 이름. 같은 날 두 공휴일은 위 표에서 한 이름으로 적는다. */
export function getHolidays(year: number): Map<string, string> {
  const h = new Map<string, string>()
  for (const [md, name] of SOLAR) {
    // 제헌절·노동절은 2026년부터 — 연도별 표에서만 넣는다
    h.set(`${year}-${md}`, name)
  }
  for (const [md, name] of BY_YEAR[year] ?? []) {
    const key = `${year}-${md}`
    const prev = h.get(key)
    // 양력 공휴일과 겹치는 날은 연도별 표의 이름(예: '추석·개천절')이 이긴다
    h.set(key, prev && !name.includes(prev) && !name.startsWith('대체') ? `${prev}·${name}` : name)
  }
  return h
}

const key = (y: number, m: number, d: number) =>
  `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`

/**
 * 신고·납부 기한이 토·일요일이나 공휴일이면 다음 영업일로 미룬다(국세기본법 제5조).
 * 달을 넘어가면 그 달 마지막 날 다음 숫자(예: 32)를 그대로 돌려준다 — 부르는 쪽이
 * "다음 달로 넘어감"을 판단한다.
 */
export function nextBusinessDay(year: number, month: number, day: number, holidays: Map<string, string>): number {
  let d = day
  for (let i = 0; i < 14; i++) {
    const date = new Date(year, month - 1, d)
    const dow = date.getDay()
    const isHoliday = holidays.has(key(date.getFullYear(), date.getMonth() + 1, date.getDate()))
    if (dow !== 0 && dow !== 6 && !isHoliday) return d
    d++
  }
  return d
}
