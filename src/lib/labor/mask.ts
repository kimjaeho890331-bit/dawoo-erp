/**
 * 주민등록번호 뒷자리를 가린다: 900101-1234567 → 900101-1******
 *
 * 근무관리 표는 권한 제한 없이 누구나 열 수 있어서, 칸을 누르지 않았을 때는 가려서 보여준다.
 * 칸을 눌러 고칠 때와 엑셀로 내보낼 때는 원래 번호를 그대로 쓴다(신고에 필요하다).
 * 형식이 맞지 않는 값(아직 쓰다 만 값 등)은 손대지 않는다.
 */
export function maskResidentId(value: string): string {
  const m = value.trim().match(/^(\d{6})-?(\d)(\d{6})$/)
  if (!m) return value
  return `${m[1]}-${m[2]}******`
}
